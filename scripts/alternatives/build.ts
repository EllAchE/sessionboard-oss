function writeOut(path: string, content: string, check: boolean, stale: string[]): void {
  const rel = relative(REPO_ROOT, path);
  let current: string | null = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    current = null;
  }
  if (current === content) return;
  if (check) {
    stale.push(current === null ? `${rel} is missing` : `${rel} is out of date`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, 'utf8');
  console.log(`  wrote ${rel}`);
}

function main(): void {
  const check = process.argv.includes('--check');
  const survey = loadSurvey();

  const problems = validate(survey);
  if (problems.length > 0) {
    console.error(`docs/alternatives/data/ is inconsistent (${problems.length} problems):`);
    for (const problem of problems) console.error(`  - ${problem}`);
    process.exit(1);
  }

  const stats = summarize(survey);
  let requirementsSource: string;
  try {
    requirementsSource = readFileSync(REQUIREMENTS_PATH, 'utf8');
  } catch {
    requirementsSource = REQUIREMENTS_SCAFFOLD;
  }

  const stale: string[] = [];
  writeOut(SURVEY_JSON_PATH, `${JSON.stringify(stats, null, 2)}\n`, check, stale);
  writeOut(MATRIX_PATH, renderMatrix(survey), check, stale);
  writeOut(VISUAL_PATH, renderVisual(survey), check, stale);
  writeOut(
    REQUIREMENTS_PATH,
    applyGeneratedBlocks(requirementsSource, renderRequirementBlocks(survey)),
    check,
    stale,
  );

  if (check) {
    if (stale.length > 0) {
      console.error('Derived files are stale — run `bun run alternatives:build` and commit the result:');
      for (const item of stale) console.error(`  - ${item}`);
      process.exit(1);
    }
    console.log(`alternatives: data valid and all derived files current (${stats.counts.analyzed} projects).`);
    return;
  }

  console.log(
    `alternatives: ${stats.counts.analyzed} analyzed of ${stats.counts.submissionsFound} found · ` +
      `${stats.counts.totalFeatureRows} feature rows · ${stats.counts.attributions} attributions.`,
  );
}

main();
